#!/usr/bin/env python3
"""Inspect and edit an AERA browser runtime payload (AERAWEB1).

The recovery must not modify the browser runtime that the plugin store ships:
audio support belongs to /system/etc/aera-gst-plugins. This tool removes
recovery-injected members from an existing runtime.xz and regenerates the
matching manifest, exactly as aeraui/features/browser/pack.py would.

    ./tools/aera-payload.py list    <runtime.xz> [substring]
    ./tools/aera-payload.py extract <runtime.xz> <path> <destination>
    ./tools/aera-payload.py remove  <runtime.xz> <path> [<path> ...]
"""
import hashlib
import json
import struct
import subprocess
import sys
from pathlib import Path

MAGIC = b"AERAWEB1"
XZ_ARGS = ["xz", "-c", "--threads=1", "--check=crc32", "--arm64",
           "--lzma2=preset=9e,lc=2,lp=2"]


def read_members(payload):
    raw = subprocess.run(["xz", "-dc", str(payload)], check=True,
                         capture_output=True).stdout
    if raw[:8] != MAGIC:
        raise SystemExit("not an AERAWEB1 payload")
    (count,) = struct.unpack_from("<I", raw, 8)
    offset = 12
    members = []
    for _ in range(count):
        name_len, mode, size = struct.unpack_from("<HHQ", raw, offset)
        offset += 12
        name = raw[offset:offset + name_len].decode("utf-8")
        offset += name_len
        offset += -offset % 4
        data = raw[offset:offset + size]
        offset += size
        members.append((name, mode, data))
    return members


def write_payload(members, payload):
    expanded = bytearray(MAGIC + struct.pack("<I", len(members)))
    manifest = []
    for name, mode, data in members:
        encoded = name.encode("utf-8")
        expanded += struct.pack("<HHQ", len(encoded), mode, len(data))
        expanded += encoded
        expanded += b"\0" * (-len(expanded) % 4)
        expanded += data
        manifest.append(dict(path=name, mode=mode, size=len(data),
                             sha256=hashlib.sha256(data).hexdigest()))
    expanded_hash = hashlib.sha256(expanded).hexdigest()
    payload.write_bytes(subprocess.run(
        XZ_ARGS, input=bytes(expanded), check=True, capture_output=True).stdout)
    compressed_hash = hashlib.sha256(payload.read_bytes()).hexdigest()

    out = payload.parent
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (out / "aera_browser_payload.hpp").write_text(
        "// Generated by browser/pack.py; do not edit.\n#pragma once\n"
        "#include <cstdint>\nnamespace aeraui::web {\n"
        f"constexpr uint64_t kCompressedBytes = {payload.stat().st_size}ULL;\n"
        f"constexpr uint64_t kExpandedBytes = {len(expanded)}ULL;\n"
        f'constexpr char kCompressedHash[] = "{compressed_hash}";\n'
        f'constexpr char kExpandedHash[] = "{expanded_hash}";\n'
        f"constexpr uint32_t kMemberCount = {len(members)};\n}}\n")
    print(json.dumps(dict(compressed=payload.stat().st_size,
                          expanded=len(expanded), files=len(members),
                          sha256=compressed_hash), indent=2))


def main(argv):
    if len(argv) < 3:
        raise SystemExit(__doc__)
    command, payload = argv[1], Path(argv[2]).resolve(strict=True)
    members = read_members(payload)
    if command == "list":
        for name, mode, data in members:
            if len(argv) > 3 and argv[3] not in name:
                continue
            print(f"{mode:04o} {len(data):>9} {name}")
        return
    if command == "extract":
        want, destination = argv[3], Path(argv[4])
        for name, mode, data in members:
            if name != want:
                continue
            destination.write_bytes(data)
            destination.chmod(0o755 if mode & 0o111 else 0o644)
            print(f"extracted {name} -> {destination} ({len(data)} bytes)")
            return
        raise SystemExit(f"absent: {want}")
    if command != "remove":
        raise SystemExit(__doc__)
    drop = set(argv[3:])
    kept = [m for m in members if m[0] not in drop]
    for name, _, _ in members:
        if name in drop:
            print(f"removed {name}")
    missing = drop - {m[0] for m in members}
    for name in sorted(missing):
        print(f"absent  {name}")
    write_payload(kept, payload)


if __name__ == "__main__":
    main(sys.argv)
